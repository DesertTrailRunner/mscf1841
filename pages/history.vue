      <h2>History of The Monroe Street Cemetery</h2>
      <p>Monroe Street Cemetery has remained public under three jurisdictions: Brooklyn Township, Ohio City, and Cleveland. Brooklyn Township acquired its cemetery when Josiah Barber and his brother-in-law, Richard Lord, sold part of lot no. 69 in the Lord &amp; Barber Subdivision in January 1836 for $160, to be used “forever as a public burying ground.”</p>
      <p>When Ohio City was incorporated on March 3, 1836, the township cemetery became the city cemetery, although perfecting its title was accomplished by another deed (1841). The Ohio City council legislated rules and regulations, appointed a sexton, and arranged for systematic platting, as well as for the purchase and storage of a hearse. When, in 1854, Ohio City was annexed to Cleveland, the cemetery became simply known as “the west side cemetery.” Until the late 1890s, it was Cleveland’s only west side public cemetery. When Cleveland opened West Park (1900) on Chestnut Ridge Rd., the dearth of west side burial sites was alleviated. Still, Monroe Street, taking over 400 burials annually, went into the 20th century as the second busiest municipal cemetery, after Woodland Cemetery. Under Cleveland’s charge, Monroe Street Cemetery, which became the more frequently used name, was ornamented with walks and plantings, protected by a patrolman, and fenced during the 19th century to keep out wandering hogs.</p>
