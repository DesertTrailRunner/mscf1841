      <h2>White Bronze Headstones</h2>
      <h3>Amid the Monroe Street mausoleums and headstones made of granite, marble and sandstone stand 29 unique, blue-gray colored markers which, when tapped, emit a hollow, metallic sound. These markers, made of “white bronze,” are truly a Victorian era phenomenon. Varying in size, shape, and decoration, they were all produced within a forty year time span, ca. 1873 to ca. 1913 but are not found universally since many cemeteries banned their use.</h3>
      <p>
        In the mid 1870s, the Monumental Bronze Company, a foundry in
        Bridgeport, Connecticut, began experimenting with metals looking for a
        way to create metal markers which would not allow lichen and mosses to
        grow on them (as they do on granite) nor erode as often happens to
        marble. The foundry was also interested in finding a metal and method
        which would allow designs that would attract people of the Victorian
        era.
      </p>
      <p>
        By the end of the decade, the company had refined a formula for
        making marketable memorials from zinc. Separate pieces were cast in
        sand. Then they were clamped together and fused by pouring boiling zinc
        along the joints. In order to give the monument the texture of granite,
        it was sandblasted. It was then brushed with a chemical which
        immediately produced the distinctive blue-gray color of the metal.
      </p>
      <p>
        The markers were made in Connecticut and by subsidiaries in
        several other cities on the East Coast and in the Midwest. Salesmen
        using catalogs showed customers the variety of monuments which were
        available. These models varied greatly in size, style and decorations.
        Panels were available to buyers. These panels could be decorated with a
        wide variety of designs including various flowers, anchors, crosses,
        etc. They also held the information concerning the person commemorated.
        Once ordered, these panels were attached to the selected monument by
        screws with ornamental heads.
      </p>
      <p>
        After the memorial and panels were chosen, the monument was
        made and shipped from the foundry. The cost of the marker was usually
        less than one made of stone and prices varied from $2.00 to $5,000. They
        were also much lighter so that shipping costs were less and they were
        much easier to handle and install.
      </p>
      <p>
        White Bronze memorials reached their popularity peak in the
        1880s-1890s. The popularity was short-lived. By the turn of the century
        only the original foundry still made the monuments. During World War I,
        metals were primarily being used for war purposes. In 1939 the company
        was liquidated.
      </p>
